CREATE TABLE IF NOT EXISTS jadwal_petugas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  jadwal_id bigint NOT NULL REFERENCES jadwal(id) ON DELETE CASCADE,
  petugas_id integer NOT NULL REFERENCES petugas(id) ON DELETE RESTRICT,
  urutan integer NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT jadwal_petugas_petugas_unique
    UNIQUE (jadwal_id, petugas_id),
  CONSTRAINT jadwal_petugas_urutan_unique
    UNIQUE (jadwal_id, urutan),
  CONSTRAINT jadwal_petugas_urutan_check
    CHECK (urutan > 0)
);

CREATE INDEX IF NOT EXISTS jadwal_petugas_petugas_idx
  ON jadwal_petugas (petugas_id);

DO $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM information_schema.columns
    WHERE table_name = 'jadwal'
      AND column_name = 'petugas_id'
  ) THEN
    INSERT INTO jadwal_petugas (jadwal_id, petugas_id, urutan)
    SELECT
      j.id,
      j.petugas_id,
      1
    FROM jadwal j
    WHERE j.petugas_id IS NOT NULL
    ON CONFLICT (jadwal_id, petugas_id) DO NOTHING;
  END IF;
END;
$$;

UPDATE jadwal j
SET jumlah_petugas = sub.assigned_count
FROM (
  SELECT jadwal_id, count(*)::integer AS assigned_count
  FROM jadwal_petugas
  GROUP BY jadwal_id
) sub
WHERE sub.jadwal_id = j.id
  AND j.jumlah_petugas < sub.assigned_count;

